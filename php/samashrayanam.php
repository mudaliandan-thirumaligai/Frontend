          <h2><strong>4) Mantram:</strong></h2>
          
          <h5 align="justify">To get the initiation of "Rahasya Traya MantrAs" - <br>
          <strong><br>
          Thirumantram -</strong> revealed by Lord as Sage Narayana to his disciple Nara in Badrikasrama.<strong><br>
          Dvayam  -   </strong>revealed by Lord to His consort Sri in Thirupaarkadal. <strong><br>
          Charama slokam -   </strong>revealed by Lord Krishna to Arjuna on the chariot in the battlefield of Kurukshetra.<br>
          <br>
          Eventhough all the five samskArams are highly important, Mantra SamskAram is the most important amongst them. The Rahasya traya (3 secrets) mantrAs are initiated to the sishyA. They are the Thirumantram (AshtAksharam), Dvayam and the Charama slokam.<br>
        <br>
           <img src="images/samashrayanam/mantram.png" alt="" width="133" height="149" class="alignleft"> 
 <strong>Plese learn Thirumantram and Dvaya Mantram from Acharya <br>
          during Samashrayanam as he is one who is Qualified to teach it to Sishyas </strong></span><br>
  <br>
  Note: <br>
  <strong>Thirumantram can be recited only in the morning after bath. <br>
  Dvayam, there is no restrictions. Tell as many times regardless of place and time</strong>.<br />
  <br>
          Thirumantram japam must be performed daily. Thirumantram japam gives all benefits that one can derive from different mantrAs. More importantly, it facilitates the bondage between the person performing the japam and Sriman NArAyanA for SaranAgati (Prapatti).<br>
          <br>
          Dvaya Mantram consists of two lines. It is also called as the 'Mantra RatnA' (Gem/Jewel amongst all the MantrAs). This helps one to perform SaranAgati unto Sriman NArAyanA. Once this mantrA is initiated by the AchAryA, it should be recited constantly within ourselves. It is infact an instruction from <a href="ramanujar.php" target="blank"><strong>BhagavAd Ramanuja</strong></a> that Dvayam should be chanted for maximum time possible.<br>
          <br>
          Charama slokam is the famous sloka of Srimad Bhagavad GitA. It is a secret because of its invaluable hidden truth. Sriman NArAyanA during His Krishna AvatArA did the Gita UpadesA to all the people through ArjunA. Since Bhakti YogA was highly difficult even for ArjunA, KrishnA out of His Mercy asked him (all the people) to perform 'Prapatti', as a means of God-Realisation.<br>
          <br>
          <strong>Charama Slokam:        </strong>(Bhagavad Gita 18:66)<br />
