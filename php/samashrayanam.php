            <strong>Who is called as Acharya? </strong><br />
            <br />
            AchArya means the one who is the foremost among the Vaidhikas (vaidikAgresara), who has devotion to Bhagavan, who is without egoism, who understands the thirumantram according to the correct meaning - that thirumantram is the essence of all the Vedas, the case of all mantras, the document for the inseparable relationship of the soul and the Lord, the savior of Mumukshus, who has no interest in artha and kAma but yet lives within the world and follows  the  dharma, artha, kAma (lokaparigraha) [and hence practices dharma, artha and kAma] -- by <strong>Sri Periyavachan Pillai </strong><br />
            <strong><br />
            What is Samashrayanam?</strong> <br />
            <br />
            SamAshrayanam means 'to approach (AchAryA) with all sincerity'. During 'SamAshrayanam', the AchAryA initiates a person, irrespective of caste, creed or sex, as his sishyA. It is a commitment from the sishya that he or she will live as per the wishes of the AchAryA. Thus the person gets the link to the Sri Vaishnava sampradayam. Pancha SamskAram (five Purifications) is performed and then he becomes a &quot;Sri VaishnavA&quot;. <br />
