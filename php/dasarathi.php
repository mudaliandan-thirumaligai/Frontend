<h4 align="center"> Swami Manavala Mamunigal sloka on Sri Mudaliandan:</h4><br />

<h5 align="center">ய: பூர்வம் பரதார்த்தித: பிரதிநிதம் ஸ்ரீபாதுகாமாத்மந: | <br />
  &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;ராஜ்யாய ப்ரததௌ ஸ ஏவ ஹி குரு: ஸ்ரீதாஸரத்யாஹவய: || <br />
                பூத்வா லக்ஷ்மண பாதுகாந்திமயு கேஸர்வாத்மநாம் ஸ்ரேயஸே | <br />
  &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;ஸாம்ராஜ்யம் ஸவயமத்ர நிர்வஹதி நோ தைவம் குலஸ்யோத்தமம் ||||<br />
<br />
Ya: Poorvam Bharathaarthitha: Prathinithim Sripaadhukaathmana: |<br />
Raajyaya Prathathou Sa Yeva he Guru: Sridasarathyahavaya: ||<br />
Boothva Lakshmana padukanthimayu Kesarvaathmanaam Sreyase |<br />
Saamrajyam Swayamathra Nirvahathi No Thaivam Kulasyothamam ||||<br />
<br />
  </h5>
<h5 align="justify"> Meaning: <strong>The one who was worshipped by Bharatha in the earlier yuga and had given his Paadhuka (Footwear) to Bharatha for ruling the kingdom on behalf of him, that Lord Rama himself have born again as Daasarathi (Mudaliandan Acharyan) to uplift all Jeevathmaa (Individual Soul) to attain moksha, is now ruling the Srivaishnava Samrajyam (Lord Vishnu devotees Kingdom)</strong>.<br />
