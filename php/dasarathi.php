<u><strong>Meaning</strong></u>: <br />
<br />
<strong>Ajahadh bhaagineyathvam</strong> - Eldest of <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja's</strong></a> sisters son is <strong>Mudaliandan</strong>. One day, when <a href="ramanujar.php" target="blank"><strong>Ramanujar</strong></a> sacrificed everything at the time of taking Sannyaasam (ascetic) he did not give up Daasarathi, as that order demanded that all kith and kin should be renounced. To this <strong><a href="ramanujar.php" target="blank"><strong>Ramanujar</strong></a> replied that Daasarathi was an exception as if he leave Mudaliandan,  means he leaves Lord Rama</strong> and said he don't want to be ascetic without Mudaliandan and added &quot;If it is possible for me an ascetic to give up my staff, only then can Daasarathi leave me. He, though a bodily relation, is yet a kin to my soul. Because <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja</strong></a> knows that Mudaliandan is Lord Rama's avatar or amsam.&quot;</h5>
<h5 align="justify">&nbsp;</h5>
<h5 align="justify"><img src="images/dasarathi/ramar.jpg" alt="" width="657" height="376" /><br />
  <br />
  <strong>paadhukaathvam</strong> - <a href="dasarathi.php" target="blank"><strong>Swami Mudaliandan</strong></a> is called as <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja's</strong></a> Lotus Feet or thiruvadi nilai. Sriman Narayana's thiruvadi is Sri Satagopan (<a href="nammazhwar.php" target="blank"><strong>Swami Nammazhwar</strong></a>). Swami Nammazhwar's thiruvadi is Madhurakavigal at all places except at Azhwaarthirunagari where it is called Sri Ramanujan. <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja's</strong></a> thiruvadi nilai is <a href="dasarathi.php" target="blank"><strong>Sri Mudaliandan</strong></a> at all places except at thirumala where it is called Ananthaazhwaan.<br /> 
  <br />
  <strong>thridhandathaam</strong> - When Thirukoshtiyur Nambi asked <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja</strong></a> to come to him to learn  the &quot;Rahasya Granthas&quot; with his Pavithram (flag which is tied up on the top of Tridandam) and Tridandam (triple staff) he took with him <a href="kooresa.php" target="blank"><strong>Koorathazhwaan</strong></a> and <a href="dasarathi.php" target="blank"><strong>Mudaliandan</strong></a> saying  that they were his Pavithram and Tridandam. <a href="dasarathi.php" target="blank"><strong>Mudaliandan's</strong></a> impeccable  service to his mentor secured for him the status of being Ramanuja's Padukas (lotus feet), Tridandam &amp; also the position of the administrator of the  Srirangam Temple.<br />
  <br />
  In our Srivaishanava Sampradayam, Pontiffs carry triple staff (tridandam) made out of three small wooden sticks. This is to signify the three components of our philosophy - chit, achit and easwara. It is mandatory for our Pontiffs to carry tridanda always with them. It is also said that &quot;Vishnuroopam Tridandagyam&quot; i.e., Tridandam is Vishnu's roopam. As Andaan is Mahavishnu's amsam, it is said &quot;Paki Neyas Tridandaga&quot;. Thus it is appropriate that he is called as Sri Ramanuja's triplestaff (Tridandam).<br />
  <br />
  <strong>sampraaptham yathiraajasya vandhe dhaasharathim gurum</strong> - so much attached with <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja</strong></a> is <a href="dasarathi.php" target="blank"><strong>Mudaliandan</strong></a> who is our acharya (guru).<br />
