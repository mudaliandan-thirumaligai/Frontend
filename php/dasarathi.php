  <br />
  <strong>Sri Ramancha samavistam pancha janyamcha sambhavam </strong>|<strong><br />
  </strong></h5>
<h5 align="justify"><strong>Pancha Narayana sthana sthapakam gurum asraye </strong>||<br />
  <br />
  <u><strong>Meaning</strong></u>: I take the solace under Acharya <a href="dasarathi.php" target="blank"><strong>Mudaliandan</strong></a>, in whom Lord Rama's partial influence and  a part of panchajanya's influenece exists is the one who installed the Pancha Narayana temples.<br />
