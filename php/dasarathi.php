<br />  
  The first sishya of <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja</strong></a> and that is why he is called as <a href="dasarathi.php" target="blank"><strong>MUDALIANDAN</strong></a>.<br />
  <br />
  
  Vishwaksenar or Sena Mudaliyaar is said to be the chief of the army of Lord Sriman Narayana. As Daasarathi ruled the Srirangam Temple Administration like Senai Muthaliyaar (Sri Vishvaksena), Daasarathi was given the name Mudaliandan by <a href="ramanujar.php" target="blank"><strong>Swami Ramanujar</strong></a>. <br />
  
<br />
    <strong>Daasarathi </strong>(given by parents)<strong>, <a href="ramanujar.php" target="blank"><strong>Yathiraja's</strong></a> paduka, Nam Vadhoola Desikan </strong>(given by Sri Ranganthar)<strong>, Vaishnav Siro Bushaa, Aandan </strong>(given by <a href="ramanujar.php" target="blank"><strong>Swami Ramanujar</strong></a>)<strong>, Tridandam </strong>(given by <a href="ramanujar.php" target="blank"><strong>Swami Ramanujar</strong></a>)<strong>, Sri Vaishnava dasar </strong>(given by Sishya's)  was a<strong> relative, disciple</strong> and<strong> associate</strong> of <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja,</strong></a> the codifier of the philosophy of Srivaishnavism. <br />
