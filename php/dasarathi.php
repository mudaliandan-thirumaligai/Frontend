    vaadhoola kuladhaureyam vandhe daasarathim gurum ||</strong><br />
    <br />
    <strong><u>Meaning</u></strong>: This thanian was rendered by <a href="dasarathi.php"><strong>Mudaliandan</strong></a> sishyas at the time when he served Periya Nambi's Daughter Athuzhai as seedhanai vellaati (like bride servant) for 6 months.<br />
