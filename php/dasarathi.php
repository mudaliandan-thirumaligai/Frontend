<h5 align="justify">It is interesting to note that Daasarathi (Mudaliandan) <strong>முதலியாண்டான்</strong>  is considered as being an Avathara of the Lord Himself. It seems that Lord Rama was so pleased with Adiseshan's service to him as Lakshmana that he wanted to serve him in future Avatharas. As a result, he bestowed the Avathara of Balarama to Adiseshan and himself as Sri Krishna. Still unable to fulfill his desire, Lord Rama took the avatar of Mudaliandan inorder to pay his reverences to <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja</strong></a>.<br />
