<h5 align="justify"><u><strong> Sri Mudaliandan Sripada Theertham</strong></u>:<br />
 <br />
 Before reaching Melkote, <a href="ramanujar.php" target="blank"><strong>Udayavar</strong></a> and Aandan halted at a place known as Thondanur. <br />
 <br />
 <a href="images/dasarathi/Mudali Vaibhav 2014 - 31 copy.jpg"><img src="images/dasarathi/Mudali Vaibhav 2014 - 31 copy.jpg" alt="" width="209" height="253" /></a>&nbsp;&nbsp;<a href="images/dasarathi/Mudali Vaibhav 2014 - 32 copy.jpg"><img src="images/dasarathi/Mudali Vaibhav 2014 - 32 copy.jpg" alt="" width="209" height="253" /></a>&nbsp;&nbsp;<a href="images/dasarathi/Mudali Vaibhav 2014 - 33 copy.jpg"><img src="images/dasarathi/Mudali Vaibhav 2014 - 33 copy.jpg" alt="" width="209" height="253" /></a><br />
<br />
 There were lot of Jainist People living there. <a href="ramanujar.php" target="blank"><strong>Swami Ramanujar</strong></a> tried to explain them about Vishistadvaita Philosophy, but in vain. Then <a href="ramanujar.php" target="blank"><strong>Swami Ramanujar</strong></a> instructed Mudaliandan to just step into the waters to wash his feet of the local pool and come out. As ordained by <a href="ramanujar.php" target="blank"><strong>Ramanuja</strong></a>, Mudaliandan interred his feet in the water at the shore from where people of the village draw water. Next day, Jainist villagers who came to take water from the lake are said to have unknowingly been converted to gentle ways (Sattva Guna - Sattva Guna is a force favourable for the attainment of Moksha) by imbibing the pool-water sanctified as the washing of Mudaliandan's feet (Sripadha - Theertham). <br />
 <br />
On the other side of the shore where the sanctified water was flowing, Vaduga Nambi collected that water in his hands where <a href="ramanujar.php" target="blank"><strong>Ramanuja</strong></a> and Andan were standing and told Ramanuja "Is it not that Andan himself is your feet (padhuka)? Therefore his Sripadha Theertham is your Sripadha Theertham. Adiyen is re-offering the theertham at your lotus feet."<br />
 <br />
 Then <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja</strong></a> said &quot;Oh ! Is this a dual Saligramam?  If so, let daily Thiruvaradhana be performed to Mudaliandan's Sripadha Theertham at this very place.&quot;<br />
<br />
 So it is firmly believed that even today who ever takes Sri Mudaliandan Sripadha Theertham will be changed to Sattva guna leaving Rajo Guna and Tamo Guna. <br />
 <br />
 That is why even today, Sri Padha Theertham at Swami Mudaliandan Thirumaligai is given to anyone without considering the Caste or Religion as it has the power to change anyone to good and noble person. <br />
 <br />

 <strong>Guna - </strong>Quality or Attribute 
<strong> <br />
 Sattva </strong>- Is the light, the purity, the kindness charity and compassion (It will develop clarity, Briskness, Understanding capability, Develop Knowledge)<br />
 <strong> Rajo  </strong>- is ego, bravery, jealousy, wars, struggles and helping with a motive (It will create anger and desire)<br />
 <strong> Tamo </strong> - is inertia, selfishness, shrewdness troubling others and keeping everything without progress. (It will make you feel sleepy, lazy, ignorant)
