  <br />
  It is believed that Lord Rama was very impressed by Thiruvananthazvan's kainkaryam as Lakshmana to him (Lord Rama) in Ramavatharam and wanted to wanted to serve him in future Avatharas. Thus, when he was born as Krishna in Krishnavataram he performed kainkaryam to Balarama (Who in turn is Thiruvananthazvan's amsam). Not fully satisfied with this, when Thiruvananthazvan appeared as Swami <a href="ramanujar.php" target="blank"><strong>Ramanuja</strong></a> in Kaliyuga, lord incarnated as Mudaliandan and did kainkaryam to Sri Ramanuja and felt satisfied. Thus Mudaliandan is an amsam of Lord Rama.<br />
  <br />
  Vaadhoola Kula Thilaka Sri Anantha Naarayana Dikshithar and Nachiyarammal (<a href="ramanujar.php" target="blank"><strong>Swami Ramanuja's</strong></a> sister) didn't have child for a long time and wish to have one and in order to get blessed with a child they prepare to go to Tirumala to pray and plead with perumal for a child. In the pilgrimage, when they were resting on one night, Lord Rama who was their Thiruvaradhana Perumal appeared in their dream and said "You don't have to go Thirumala. I will myself be born as your son. Name him as "Daasarathi"". Daasarathi refers to the sons of King Dasaratha like how Lord Rama was also called.<br />
  <strong><br />
    Daasarathi (Mudaliandan) is an amsam or avatar of Lord Sri Rama.</strong><br />
  <br />
  Swami Mudaliandan was born in Prabhava Year, Chithirai Month, Punarpoosam Natchathiram (1027) at <a href="pettai.php" target="blank"><strong>Pachai Varana Puram</strong></a> (referred to as &quot;<a href="pettai.php" target="blank"><strong>NazarethPettai</strong></a>&quot; today) in Thondai mandalam, in the state of Tamil Nadu in South India. His parents were Vaadhoola Kula Thilaka Sri Anantha Naarayana Dikshithar and Nachiyarammal (<a href="ramanujar.php" target="blank"><strong>Sri Ramanuja's</strong></a> sister). Daasarathi, as he was named, was Ramanuja's Priya Bhagineya in the parlance of the age. Born to his service, and known as &quot;Yathiraaja Paaduka&quot;, he enjoyed a special relationship with <a href="ramanujar.php" target="blank"><strong>Swami Ramanujar</strong></a> all his life.<br />
  <br />
  </h5>
<h5 align="justify"><img src="images/dasarathi/ramanuja.jpg" alt="" width="657" height="376" /></h5>
<h5 align="justify"><br />
  Nachiyarammal was the eldest of <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja's</strong></a> two sisters. Hence Mudaliandan is called as <a href="ramanujar.php" target="blank"><strong>Sri Ramanuja's</strong></a> Bhagineyar (sister's son). Anantha Narayana Dheekshidar named the child as Daasarathi. He was born in <strong>Vadamal Kulam, Vadhoola Gothram, Yajus sakhaai, Apasthamba Soothram in Prabava varusham, Chithira masam, Punarvasu natchathiram, an amsam of Lord Sri Rama.</strong><br />
  <br />
  <u><strong>Early Life</strong></u>:<br />
  <br />
  Having begun his learning with his father, Daasarathi became a pillar of support to <a href="ramanujar.php" target="blank"><strong>Swami Ramanujar</strong></a>, acclaimed by him as being identical to his Tridandam - his staff office as a sanyasi. However, <a href="ramanujar.php" target="blank"><strong>Swami Ramanujar</strong></a> kept him busy in many ways, as he was a capable executive and administrator. 
  
  <br />
  <br />
  <a href="ramanujar.php" target="blank"><strong>Sri Ramanuja</strong></a>, later started to depend on Daasarathi a lot. While going to kaveri for his daily bath, he used to lean on Daasarathi for support. <br />
  <br />
  One day, when <a href="ramanujar.php" target="blank"><strong>Sri Ramanuja</strong></a> sacrificed everything at the time of taking Sannyaasam (ascetic) he did not give up Daasarathi, as that order demanded that all kith and kin should be renounced. To this <a href="ramanujar.php" target="blank"><strong>Sri Ramanuja</strong></a> replied that Daasarathi was an exception as he was his triplestaff (tridandam) (the same reason he gave to Tirukkottiyur Nambi) and added &quot;If it is possible for me an ascetic to give up my staff only then can Daasarathi leave me. He, though a bodily relation, is yet a kin to my soul. Because <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja</strong></a> knows he is Lord Rama's avatar or amsam.&quot; <br />
  <br />
  Thus Daasarathi became the first and Foremost disciple and thus how he was named as Mudali Andan by <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja</strong></a>
  
  He was later to be known as "Sriranganaatha Divyaalaya Nirvahana Dhurandhara" - the genius who organized, under <a href="ramanujar.php" target="blank"><strong>Ramanuja's</strong></a> tutelage, the administration of the Sri Ranganathaswamy Temple.
  
  <br />
  <br />
  He is mentioned in the Koyil Ozhugu, the chronicle of Sri Ranganathaswamy Temple, in glowing terms,
  
  <br />
  <br />
  <strong>"muthaliyaandaanum kurattilirunthu koyil kariyaththaiyum uLLe karuvulaka vaasalileyirunthu thirumeni upachaaraththayum, sannathiyile irunthu thiruppavaLa upchaarangaLayum udayavar niyamanappadi aaraaynthu kondu anaiththazhagum kaNdarula paNNIk-kondirunthaar"</strong>.
  
  <br />
  <br />
  (Roughly translated as: Mudaliandan administered the following, according to <a href="ramanujar.php" target="blank"><strong>Swami Ramanuja's</strong></a> orders, the many works of the temple, the services to the Lord, and the works of the Shrine.)
  
  <br />
  <br />
  <u><strong>Swami Desikan on Mudaliandan's sayings:</strong></u> Mudaliandaan is most well known for his lapidary saying, here given in transliterated maNipraavaaLam: 
  
  <br />
  <br />
  <strong>"oru malaiyil ninru, oru malaiyil thaavum simha shareeraththil janthukkaL pole bhaashyakaarar samsaaralanganam paNNa avarOdundaana kudalthudakkaale naam udhdheerdaraavuthomenru muthaliyaandaruLi-ch-cheytha paasuram"</strong>.
  
  <br />
  <br />
  This is roughly translatable as follows: When a lion leaps from a mountain to another, all the creatures that live on his body go with him. Even so, when <a href="ramanujar.php" target="blank"><strong>Udayavar</strong></a> transcended this world, all of us who are associated with him benefit from this as well.
  
  <br />
  <br />
  On udayavar's instructions <a href="dasarathi.php" target="blank"><strong>Swami Mudaliandan</strong></a> went to Belur and converted all peoples to Srivaishnavism and installed Pancha Narayana temples at various locations.<br />
  <br />
